#!/usr/bin/env python3
"""
Generate motion_platform.proto from backend dataclasses.

Field numbers are derived from dataclasses.fields() in definition order,
matching UniteLabs CDK Structure.encode() which enumerates elements starting
at 1. This guarantees the generated proto can never drift from the runtime
schema as long as dataclass field order is preserved.

Usage (from repo root):
    cd software/backend
    uv run python scripts/gen_proto.py \
        > ../frontend/src/chem_bench_ui/proto/motion_platform.proto

CI drift check:
    uv run python scripts/gen_proto.py | diff - \
        ../frontend/src/chem_bench_ui/proto/motion_platform.proto
"""

import dataclasses
import sys
import typing
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from chem_bench.features.motion_platform import Position, ToolheadInfo  # noqa: E402

# Python annotation type → SiLA proto wrapper message name
_SILA_TYPE: dict[type, str] = {
    float: "Real",
    bool:  "Boolean",
    str:   "SString",
}

_HEADER = """\
syntax = "proto3";

// DO NOT EDIT — generated by software/backend/scripts/gen_proto.py
//
// Field numbers come from dataclasses.fields() definition order, matching
// UniteLabs CDK Structure.encode() which enumerates elements starting at 1.
// Any change to backend dataclass field order MUST be followed by running
// gen_proto.py and recompiling the stubs.
//
// Regenerate:
//   cd software/backend
//   uv run python scripts/gen_proto.py \\
//       > ../frontend/src/chem_bench_ui/proto/motion_platform.proto
//   python -m grpc_tools.protoc \\
//       -I ../frontend/src/chem_bench_ui/proto \\
//       --python_out=../frontend/src/chem_bench_ui/proto \\
//       ../frontend/src/chem_bench_ui/proto/motion_platform.proto

package sila2.edu.iastate.ames.chembench.motionplatform.v0;

// ── SiLA primitive wrappers ───────────────────────────────────────────────────
// Each scalar is wrapped in a length-delimited message so that the CDK can
// distinguish zero values from absent fields at the Structure layer.
message Real    { double value = 1; }
message Boolean { bool   value = 1; }
message SString { string value = 1; }

"""

_FOOTER = """
// ── Observable property parameter / response messages ────────────────────────

message Subscribe_Position_Parameters {}
message Subscribe_Position_Responses   { Position     Position     = 1; }

message Subscribe_State_Parameters {}
message Subscribe_State_Responses      { SString      State        = 1; }

message Subscribe_ToolheadInfo_Parameters {}
message Subscribe_ToolheadInfo_Responses  { ToolheadInfo ToolheadInfo = 1; }

message Subscribe_HasSavedState_Parameters {}
message Subscribe_HasSavedState_Responses  { Boolean HasSavedState = 1; }

// ── Command messages ──────────────────────────────────────────────────────────

message Empty {}

// Field order matches function signature order in motion_platform.py.
message MoveTo_Parameters        { Real    x     = 1; Real y  = 2; Real z = 3; }
message Jog_Parameters           { Real    dx    = 1; Real dy = 2; Real dz = 3; }
message EngageTool_Parameters    { Real    depth = 1; }
message DisengageTool_Parameters { Real    depth = 1; }
message SetZ_Parameters          { Real    z     = 1; }
message SetToolhead_Parameters   { SString name  = 1; }

message ListToolheads_Responses  { SString Toolheads = 1; }

// ── Service ───────────────────────────────────────────────────────────────────

service MotionPlatform {
  // Observable properties (server-streaming)
  rpc Subscribe_Position      (Subscribe_Position_Parameters)      returns (stream Subscribe_Position_Responses);
  rpc Subscribe_State         (Subscribe_State_Parameters)         returns (stream Subscribe_State_Responses);
  rpc Subscribe_ToolheadInfo  (Subscribe_ToolheadInfo_Parameters)  returns (stream Subscribe_ToolheadInfo_Responses);
  rpc Subscribe_HasSavedState (Subscribe_HasSavedState_Parameters) returns (stream Subscribe_HasSavedState_Responses);

  // Observable commands (unary initiate; response stream not consumed by client)
  rpc MoveTo        (MoveTo_Parameters)        returns (Empty);
  rpc Jog           (Jog_Parameters)           returns (Empty);
  rpc EngageTool    (EngageTool_Parameters)    returns (Empty);
  rpc DisengageTool (DisengageTool_Parameters) returns (Empty);

  // Unobservable commands
  rpc HomeAuto                (Empty)                  returns (Empty);
  rpc StartManualHoming       (Empty)                  returns (Empty);
  rpc ConfirmXMin             (Empty)                  returns (Empty);
  rpc ConfirmXMax             (Empty)                  returns (Empty);
  rpc ConfirmYMin             (Empty)                  returns (Empty);
  rpc ConfirmYMax             (Empty)                  returns (Empty);
  rpc ConfirmZReference       (Empty)                  returns (Empty);
  rpc FinishHoming            (Empty)                  returns (Empty);
  rpc SetZ                    (SetZ_Parameters)        returns (Empty);
  rpc SetToolhead             (SetToolhead_Parameters) returns (Empty);
  rpc ClearToolhead           (Empty)                  returns (Empty);
  rpc ConfirmToolheadMounted  (Empty)                  returns (Empty);
  rpc ClearToolheadMounted    (Empty)                  returns (Empty);
  rpc ListToolheads           (Empty)                  returns (ListToolheads_Responses);
  rpc SaveAndPark             (Empty)                  returns (Empty);
}
"""


def _struct_to_proto(cls: type) -> str:
    """Emit a proto3 message block from a dataclass, preserving field definition order."""
    hints = typing.get_type_hints(cls)
    lines = [f"// Generated from {cls.__module__}.{cls.__qualname__}"]
    lines.append(f"message {cls.__name__} {{")
    for i, field in enumerate(dataclasses.fields(cls), start=1):
        proto_type = _SILA_TYPE.get(hints[field.name])
        if proto_type is None:
            raise TypeError(
                f"Unsupported annotation type for {cls.__name__}.{field.name}: "
                f"{hints[field.name]!r}. Add it to _SILA_TYPE."
            )
        lines.append(f"  {proto_type} {field.name} = {i};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    out = sys.stdout
    out.write(_HEADER)
    out.write("// ── Dataclass-derived structure messages ─────────────────────────────────────\n\n")
    out.write(_struct_to_proto(Position))
    out.write("\n\n")
    out.write(_struct_to_proto(ToolheadInfo))
    out.write(_FOOTER)


if __name__ == "__main__":
    main()
