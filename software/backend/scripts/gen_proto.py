def _struct_to_proto(module: str, cls_name: str) -> str:
    import importlib
    cls = getattr(importlib.import_module(module), cls_name)
    hints = typing.get_type_hints(cls)
    lines = [f"// Generated from {cls.__module__}.{cls.__qualname__}"]
    lines.append(f"message {cls.__name__} {{")
    for i, field in enumerate(dataclasses.fields(cls), start=1):
        proto_type = _SILA_TYPE.get(hints[field.name])
        if proto_type is None:
            raise TypeError(
                f"Unsupported annotation type for {cls.__name__}.{field.name}: "
                f"{hints[field.name]!r}. Add it to _SILA_TYPE."
            )
        lines.append(f"  {proto_type} {field.name} = {i};")
    lines.append("}")
    return "\n".join(lines)


def _fields_message(name: str, fields: tuple) -> str:
    if not fields:
        return ""
    body = " ".join(
        f"{ftype} {fname} = {i};" for i, (fname, ftype) in enumerate(fields, start=1)
    )
    return f"message {name} {{ {body} }}"


def generate(device: str) -> str:
    spec = _DEVICES[device]
    out: list[str] = [_HEADER_TEMPLATE.format(device=device, package=spec.package)]

    if spec.structures:
        out.append("// Dataclass-derived structure messages\n")
        for module, cls_name in spec.structures:
            out.append(_struct_to_proto(module, cls_name))
            out.append("")

    out.append("// Observable property messages\n")
    for name, vtype in spec.streams:
        out.append(f"message Subscribe_{name}_Parameters {{}}")
        out.append(f"message Subscribe_{name}_Responses {{ {vtype} {name} = 1; }}")
        out.append("")

    out.append("// Command messages\n")
    for rpc, params, responses in spec.commands:
        if params:
            out.append(_fields_message(f"{rpc}_Parameters", params))
        if responses:
            out.append(_fields_message(f"{rpc}_Responses", responses))
    out.append("")

    out.append("// Service\n")
    out.append(f"service {spec.service} {{")
    for name, _ in spec.streams:
        out.append(
            f"  rpc Subscribe_{name} (Subscribe_{name}_Parameters) "
            f"returns (stream Subscribe_{name}_Responses);"
        )
    out.append("")
    for rpc, params, responses in spec.commands:
        req = f"{rpc}_Parameters" if params else "Empty"
        resp = f"{rpc}_Responses" if responses else "Empty"
        out.append(f"  rpc {rpc} ({req}) returns ({resp});")
    out.append("}")

    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 2 or sys.argv[1] not in _DEVICES:
        print(f"usage: gen_proto.py <{'|'.join(_DEVICES)}>", file=sys.stderr)
        sys.exit(2)
    sys.stdout.write(generate(sys.argv[1]))


if __name__ == "__main__":
    main()
