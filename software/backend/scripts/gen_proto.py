#!/usr/bin/env python3
"""
Generate a device's frontend .proto from a declarative manifest.

One generator for every device; each device contributes a _DeviceSpec entry to
_DEVICES below (package/service names, streams, commands, and optionally
dataclasses to turn into structure messages). Adding a device = adding one
manifest entry here, then `make gen-proto`.

Usage (from software/backend):
    uv run python scripts/gen_proto.py gantry          # proto text on stdout
    make gen-proto                                     # regenerate + compile all
    make check-proto                                   # CI drift check

Wire-format notes:
- Field numbers come from declaration order, matching UniteLabs CDK
  Structure.encode() / command parameter order, which enumerates starting at 1.
  Any change to backend dataclass field order or command parameter order MUST
  be followed by `make gen-proto` and a stub recompile.
- Response message *field names* are cosmetic (only numbers/types are on the
  wire); parameter names match the backend python argument names.
"""
from __future__ import annotations

import dataclasses
import sys
import typing

_SILA_TYPE: dict[type, str] = {
    float: "Real",
    bool:  "Boolean",
    str:   "SString",
}

_HEADER_TEMPLATE = """\
syntax = "proto3";

// DO NOT EDIT - generated by software/backend/scripts/gen_proto.py ({device})
//
// Field numbers come from declaration order, matching UniteLabs CDK
// Structure.encode() which enumerates elements starting at 1. Any change to
// backend dataclass field order or command parameters MUST be followed by
// running gen_proto.py and recompiling the stubs.
//
// Regenerate (from software/backend):
//   make gen-proto

package {package};

// SiLA primitive wrappers
message Real    {{ double value = 1; }}
message Boolean {{ bool   value = 1; }}
message SString {{ string value = 1; }}

message Empty {{}}

"""


@dataclasses.dataclass(frozen=True)
class _DeviceSpec:
    """Everything needed to emit one device's .proto."""

    package: str                                  # SiLA gRPC package
    service: str                                  # SiLA feature/service name
    proto_name: str                               # output file stem, e.g. motion_platform
    # (module, class name) pairs turned into structure messages
    structures: tuple[tuple[str, str], ...] = ()
    # (ObservableName, value message/wrapper type)
    streams: tuple[tuple[str, str], ...] = ()
    # (RpcName, ((param_field, Type), ...), ((response_field, Type), ...))
    # empty params -> Empty request; empty responses -> Empty response.
    commands: tuple[tuple[str, tuple, tuple], ...] = ()


