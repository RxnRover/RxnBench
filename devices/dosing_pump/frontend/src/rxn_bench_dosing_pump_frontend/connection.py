"""Dosing pump connection - human-maintained layer on top of the generated base.

Stream registration and the fire-and-forget commands are generated (see
generated_connection.py) from connection_spec.yaml. Wire encoding/decoding uses
the compiled protobuf stubs in proto/dosing_pump_pb2.py (generated by
rxnbench/backend's `make gen-proto`). The calls below stay handwritten because
they need responses rather than the generated fire-and-forget pattern.
"""
from __future__ import annotations

import threading

from PySide6.QtCore import Signal

from .generated_connection import DosingPumpConnectionBase
from .proto import dosing_pump_pb2 as _pb


class DosingPumpConnection(DosingPumpConnectionBase):
    """Human-owned dosing pump client.

    Add convenience methods and higher-level workflows here.
    Stream boilerplate is in DosingPumpConnectionBase (generated).
    """

    stopped = Signal(float)              # volume dispensed before stopping, ml
    totals_ready = Signal(float, float)  # (net total, absolute total), ml
    limits_ready = Signal(float, float)  # (max flow rate ml/min, pump voltage V)

    # --- Post-connect ---

    def _after_connected(self, gen: int) -> None:
        """Pull the slow-changing values once the channel is up."""
        self.fetch_totals()
        self.fetch_limits()

    # --- Commands needing a response ---

    def stop(self) -> None:
        """Stop dispensing (non-blocking); emits stopped() with the volume delivered."""
        threading.Thread(target=self._do_stop, daemon=True).start()

    def _do_stop(self) -> None:
        try:
            raw = self._channel.unary_unary(self._rpc("Stop"))(b"", timeout=10.0)
            resp = _pb.Stop_Responses.FromString(bytes(raw))
            self.stopped.emit(resp.VolumeDispensed.value)
            self._do_fetch_totals()
        except Exception as e:
            self.error_occurred.emit(f"Stop: {e}")

    def fetch_totals(self) -> None:
        """Request both total-volume counters from the server (non-blocking)."""
        threading.Thread(target=self._do_fetch_totals, daemon=True).start()

    def _do_fetch_totals(self) -> None:
        try:
            net = self._get_real("Get_TotalVolume", _pb.Get_TotalVolume_Responses, "TotalVolume")
            absolute = self._get_real(
                "Get_AbsoluteTotalVolume",
                _pb.Get_AbsoluteTotalVolume_Responses,
                "AbsoluteTotalVolume",
            )
            self.totals_ready.emit(net, absolute)
        except Exception as e:
            self.error_occurred.emit(f"Get totals: {e}")

    def fetch_limits(self) -> None:
        """Request the max flow rate and pump voltage from the server (non-blocking)."""
        threading.Thread(target=self._do_fetch_limits, daemon=True).start()

    def _do_fetch_limits(self) -> None:
        try:
            rate = self._get_real("Get_MaxFlowRate", _pb.Get_MaxFlowRate_Responses, "MaxFlowRate")
            volts = self._get_real("Get_PumpVoltage", _pb.Get_PumpVoltage_Responses, "PumpVoltage")
            self.limits_ready.emit(rate, volts)
        except Exception as e:
            self.error_occurred.emit(f"Get limits: {e}")

    # --- Internals ---

    def _get_real(self, rpc: str, response_type, field: str) -> float:
        """Call a no-parameter RPC and pull one Real field out of the reply."""
        raw = self._channel.unary_unary(self._rpc(rpc))(b"", timeout=5.0)
        return getattr(response_type.FromString(bytes(raw)), field).value
